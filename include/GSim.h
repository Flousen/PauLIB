#pragma once

// g-sim: Lie-algebraic simulation of parametrised Pauli circuits.
//
// Given circuit generators {h_l} (Pauli strings), the dynamical Lie algebra
// (DLA) g = <{ih_l}>_Lie is computed by Lie closure. Expectation values of
// observables O in span{h_a} evolve in the adjoint representation:
//
//     e_a(theta) = tr(h_a rho(theta)),   <O> = sum_a w_a e_a
//
// so each gate exp(-i theta h_mu) acts on the dim(g)-vector e instead of the
// 2^n-dimensional Hilbert space. For a pure-Pauli DLA basis the adjoint
// matrices are signed permutations scaled by 2, and the gate action reduces
// to independent Givens rotations:
//
//     exp(i theta P) Q exp(-i theta P) = cos(2 theta) Q + i sin(2 theta) PQ
//
// for {P, Q} = 0. Gates generated by sums of basis elements use a dense
// Eigen matrix exponential of the dim(g) x dim(g) adjoint generator.
//
// Efficiency caveat: dim(g) can grow up to 4^N - 1 for generic generators;
// g-sim is only useful when the closure stays polynomial (e.g. free-fermion /
// transverse-field Ising circuits). lie_closure() takes a max_dim guard.

#include <atomic>
#include <cmath>
#include <cstddef>
#include <cstdint>
#include <stdexcept>
#include <string>
#include <unordered_map>
#include <utility>
#include <vector>

#include <Eigen/Dense>
#include <unsupported/Eigen/MatrixFunctions>

#include "PauliString.h"
#include "PauliSum.h"

namespace paulib {

// Lie closure of a set of Pauli-string generators: repeatedly add
// [P, Q] = 2PQ (for anticommuting pairs) until no new strings appear.
// Elements are canonicalised to flags == 0 (phase absorbed into the
// structure constants). All-identity generators are ignored.
// Throws std::runtime_error when the dimension exceeds max_dim.
template <std::size_t N>
std::vector<PauliString<N>> lie_closure(const std::vector<PauliString<N>>& generators,
                                        std::size_t max_dim = std::size_t{1} << 16) {
    std::vector<PauliString<N>> basis;
    std::unordered_map<PauliString<N>, std::size_t,
                       PauliStringXZHash<N>, PauliStringXZEqual<N>> index;

    auto try_insert = [&](PauliString<N> p) {
        p.flags = 0;
        if (index.count(p)) return;
        if (basis.size() >= max_dim)
            throw std::runtime_error("lie_closure: DLA dimension exceeds max_dim = " +
                                     std::to_string(max_dim));
        index.emplace(p, basis.size());
        basis.push_back(p);
    };

    std::size_t nq = 0;
    for (const auto& g : generators) {
        nq = std::max(nq, g.num_qubits());
        bool identity = true;
        for (std::size_t k = 0; k < PauliString<N>::ArraySize; ++k)
            if (g.x[k] | g.z[k]) { identity = false; break; }
        if (!identity) try_insert(g);
    }

    // basis grows while iterating; every unordered pair (j < i) is visited
    // exactly once.
    for (std::size_t i = 1; i < basis.size(); ++i)
        for (std::size_t j = 0; j < i; ++j)
            if (basis[i].anti_commute(basis[j]))
                try_insert(basis[i] * basis[j]);

    for (auto& b : basis) b.num_qubits_ = static_cast<uint32_t>(nq);
    return basis;
}

template <std::size_t N, typename T = double>
class GSim {
public:
    using Vec = Eigen::Matrix<T, Eigen::Dynamic, 1>;
    using Mat = Eigen::Matrix<T, Eigen::Dynamic, Eigen::Dynamic>;
    static constexpr std::size_t npos = static_cast<std::size_t>(-1);

    struct Gate {
        std::size_t mu;  // basis index of the generator
        T theta;
    };

    explicit GSim(const std::vector<PauliString<N>>& generators,
                  std::size_t max_dim = std::size_t{1} << 16)
        : basis_(lie_closure(generators, max_dim)) {
        for (std::size_t a = 0; a < basis_.size(); ++a) index_.emplace(basis_[a], a);
        build_rotations();
    }

    std::size_t dim() const { return basis_.size(); }
    const std::vector<PauliString<N>>& basis() const { return basis_; }

    // Index of p in the DLA basis (phase prefix ignored), or npos.
    std::size_t basis_index(const PauliString<N>& p) const {
        auto it = index_.find(p);
        return it == index_.end() ? npos : it->second;
    }

    // e0_a = tr(h_a |0..0><0..0|): 1 for strings containing only I and Z.
    Vec zero_state_vector() const {
        Vec e = Vec::Zero(dim());
        for (std::size_t a = 0; a < dim(); ++a) {
            bool diagonal = true;
            for (std::size_t k = 0; k < PauliString<N>::ArraySize; ++k)
                if (basis_[a].x[k]) { diagonal = false; break; }
            if (diagonal) e[a] = T{1};
        }
        return e;
    }

    // e0_a = tr(h_a rho) for a general density operator given as a Pauli sum
    // (normalisation, e.g. the 1/2^n, must be part of rho's coefficients).
    // rho components outside the DLA cannot influence <O> for O in the DLA
    // and are ignored; imaginary parts (odd phase exponent, non-Hermitian)
    // contribute nothing to the real expectation values.
    Vec initial_vector(const PauliSum<N, T>& rho) const {
        Vec e = Vec::Zero(dim());
        if (dim() == 0) return e;
        if (rho.num_qubits() != basis_[0].num_qubits())
            throw std::invalid_argument("initial_vector: qubit-count mismatch");
        for (std::size_t j = 0; j < rho.get_length(); ++j) {
            const std::size_t a = basis_index(rho.get_pauli_string(j));
            if (a == npos) continue;
            const uint8_t k = rho.flags[j] & 0x03;
            if (k & 1) continue;
            e[a] += (k == 2) ? -rho.value[j] : rho.value[j];
        }
        return e * std::ldexp(T{1}, static_cast<int>(rho.num_qubits()));
    }

    // Weight vector of O = sum_j c_j P_j. Every P_j must be a DLA basis
    // element (invariance requirement of g-sim); a leading '-' on P_j is
    // folded into the weight.
    Vec observable_weights(const std::vector<std::pair<PauliString<N>, T>>& observable) const {
        Vec w = Vec::Zero(dim());
        for (const auto& [p, c] : observable) {
            if (p.getPhase())
                throw std::invalid_argument("observable term " + p.to_string() +
                                            " has an imaginary phase");
            const std::size_t a = basis_index(p);
            if (a == npos)
                throw std::invalid_argument("observable term " + p.to_string() +
                                            " is not in the DLA");
            w[a] += p.getSign() ? -c : c;
        }
        return w;
    }

    // Apply the gate exp(-i theta h_mu) to the expectation vector:
    // e'_a = cos(2 theta) e_a + s sin(2 theta) e_b over the precomputed
    // anticommuting pairs (a, b) of h_mu.
    void apply_gate(Vec& e, std::size_t mu, T theta) const {
        const T c = std::cos(2 * theta);
        const T s = std::sin(2 * theta);
        for (const Rotation& r : rot_[mu]) {
            const T ea = e[r.a];
            const T eb = e[r.b];
            e[r.a] = c * ea + r.sign * s * eb;
            e[r.b] = c * eb - r.sign * s * ea;
        }
    }

    // Adjoint-flow generator A_mu (antisymmetric, entries 0 / +-2), defined
    // by e(theta) = exp(theta A_mu) e(0) for the gate exp(-i theta h_mu).
    Mat adjoint_generator(std::size_t mu) const {
        Mat A = Mat::Zero(dim(), dim());
        for (const Rotation& r : rot_[mu]) {
            A(r.a, r.b) = 2 * r.sign;
            A(r.b, r.a) = -2 * r.sign;
        }
        return A;
    }

    // Gate exp(-i theta H) with H = sum_j c_j h_{mu_j} an arbitrary DLA
    // element, via a dense Eigen matrix exponential — O(dim^3).
    void apply_hamiltonian_gate(Vec& e,
                                const std::vector<std::pair<std::size_t, T>>& hamiltonian,
                                T theta) const {
        Mat A = Mat::Zero(dim(), dim());
        for (const auto& [mu, cj] : hamiltonian) {
            for (const Rotation& r : rot_[mu]) {
                A(r.a, r.b) += 2 * cj * r.sign;
                A(r.b, r.a) -= 2 * cj * r.sign;
            }
        }
        A *= theta;
        e = A.exp() * e;
    }

    // <O> = w . e after applying the circuit (gates in application order,
    // first gate acts on |0..0> first).
    T expectation(const std::vector<Gate>& circuit, const Vec& weights) const {
        Vec e = zero_state_vector();
        for (const Gate& g : circuit) apply_gate(e, g.mu, g.theta);
        return weights.dot(e);
    }

private:
    // One Givens pair of h_mu: h_mu anticommutes with h_a, h_mu h_a = i^k h_b.
    // sign = +1 for k == 3, -1 for k == 1 (from i^(k+1) in the rotation
    // formula above). Each unordered pair is stored once with a < b.
    struct Rotation {
        std::size_t a, b;
        T sign;
    };

    void build_rotations() {
        rot_.resize(dim());
        // Each rot_[mu] is filled independently; O(dim^2) pairs in total.
        // Exceptions must not escape the parallel region, so a missing basis
        // element only sets a flag and the throw happens afterwards.
        std::atomic<bool> broken{false};
        #pragma omp parallel for schedule(dynamic) if (dim() >= 256)
        for (std::size_t mu = 0; mu < dim(); ++mu) {
            for (std::size_t a = 0; a < dim(); ++a) {
                if (basis_[mu].commute(basis_[a])) continue;
                PauliString<N> p = basis_[mu] * basis_[a];
                const uint8_t k = p.flags;
                p.flags = 0;
                const std::size_t b = basis_index(p);
                if (b == npos) {
                    broken.store(true, std::memory_order_relaxed);
                    continue;
                }
                if (a < b) rot_[mu].push_back({a, b, k == 3 ? T{1} : T{-1}});
            }
        }
        if (broken)
            throw std::logic_error("GSim: basis is not closed under commutation");
    }

    std::vector<PauliString<N>> basis_;
    std::unordered_map<PauliString<N>, std::size_t,
                       PauliStringXZHash<N>, PauliStringXZEqual<N>> index_;
    std::vector<std::vector<Rotation>> rot_;
};

}  // namespace paulib
